import pandas as pd

data = {
    "Имя": ["Анна", "Иван", "Олег", "Мария", "Петр", "Света", "Дмитрий", "Елена"],
    "Группа": ["1ИИ-1", "1ИИ-1", "1ИИ-2", "1ИИ-2", "1ИИ-1", "1ИИ-2", "1ИИ-1", "1ИИ-2"],
    "Баллы": [85, 72, 91, 64, 88, 79, 55, 93],
    "Посещено занятий": [18, 15, 20, 12, 17, 16, 10, 19],
}
df = pd.DataFrame(data)
df["Баллы после бонуса"] = df["Баллы"] + 5
print("Исходная таблица:")
print(df)
print("shape:", df.shape)
print("columns:", df.columns)
print("Первые 3 строки:")
print(df.head(3))
print("Последние 2 строки:")
print(df.tail(2))
print("Средний балл:", df["Баллы"].mean())
print("Минимальный балл:", df["Баллы"].min())
print("Максимальный балл:", df["Баллы"].max())
print("Сумма посещённых занятий:", df["Посещено занятий"].sum())
print("Студенты с баллами 80 и выше:")
print(df[df["Баллы"] >= 80])
print("Студенты группы 1ИИ-1:")
print(df[df["Группа"] == "1ИИ-1"])
print("Студенты с баллами от 60 до 80:")
print(df[(df["Баллы"] >= 60) & (df["Баллы"] <= 80)])
print("Только Имя и Баллы:")
print(df[["Имя", "Баллы"]])
print("Строка через loc:")
print(df.loc[0])
print("Строка через iloc:")
print(df.iloc[1])