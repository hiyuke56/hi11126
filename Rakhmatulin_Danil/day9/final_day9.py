import pandas as pd
df = pd.read_csv("day9/students_missing.csv")
print("Первые 5 строк:")
print(df.head())
print("shape:", df.shape)
print("columns:", df.columns)
print("dtypes:")
print(df.dtypes)
df.info()
print("Пропуски по столбцам:")
print(df.isna().sum())
df["Баллы"] = df["Баллы"].fillna(df["Баллы"].mean())
df["Посещено"] = df["Посещено"].fillna(0)
df = df.dropna().reset_index(drop=True)
df["Пропущено"] = 20 - df["Посещено"]
df["Процент посещаемости"] = (df["Посещено"] / 20 * 100).round(1)
print("После очистки:")
print(df)
print("Баллы 80 и выше:")
print(df[df["Баллы"] >= 80])
print("Группа 1ИИ-1 с посещением 15 и выше:")
print(df[(df["Группа"] == "1ИИ-1") & (df["Посещено"] >= 15)])
print("Сортировка по баллам по убыванию:")
print(df.sort_values("Баллы", ascending=False))
print("Средний балл:", df["Баллы"].mean())
print("Минимальный балл:", df["Баллы"].min())
print("Максимальный балл:", df["Баллы"].max())
df.to_csv("final_result_day9.csv", index=False, encoding="utf-8")
print("Сохранено в final_result_day9.csv")